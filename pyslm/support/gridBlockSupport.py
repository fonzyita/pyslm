def _polygonal_parts(geometry: Any) -> List[shapely.geometry.Polygon]:
    if isinstance(geometry, shapely.geometry.Polygon):
        return [geometry]
    if isinstance(
        geometry,
        (shapely.geometry.MultiPolygon, shapely.geometry.GeometryCollection),
    ):
        return [
            polygon
            for part in geometry.geoms
            for polygon in _polygonal_parts(part)
        ]
    return []


