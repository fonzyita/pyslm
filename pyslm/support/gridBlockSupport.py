        # Offset the outer path to provide a clean boundary to work with
        # paths2 = np.hstack([myPolyVerts, np.arange(len(myPolyVerts)).reshape(-1, 1)])
        # paths2 = list(map(tuple, paths2))
        # clipPaths = BaseHatcher.scaleToClipper(paths2)

